"""Outgoing Certificate of Analysis for a product lot, issued only after a release check."""
from __future__ import annotations

from io import BytesIO

import numpy as np
import pandas as pd

from . import config, oos, qms
from .insight.rules import lab, num

METHOD = {"viscosity": "Rotational, 25 °C, 10 rpm", "tg": "DSC midpoint, 10 °C/min", "peak_temp": "DSC, 10 °C/min",
          "enthalpy": "DSC, 10 °C/min", "filler_pct": "TGA residue, 800 °C"}
COMPANY = "MQI Demo Plant"


def release_check(b, lot: str, oos_flags: list | None = None) -> tuple[str, list[tuple[str, str]]]:
    """'release' | 'hold' | 'block' with (ko, en) reasons.

    Values in b.product are the reportable results. The test history is checked as well, so a lot
    whose first result failed is not released just because a retest passed (see mqi.oos).
    """
    spec = config.specs()["product"]["properties"]
    row = b.product[b.product["lot_id"] == lot]
    if row.empty:
        return "block", [("로트 없음", "Lot not found")]
    r, i = row.iloc[0], row.index[0]
    reasons, level = [], "release"
    for p, s in spec.items():
        v = r.get(p)
        if v is None or pd.isna(v):
            reasons.append((f"{lab(p, 'ko')} 측정값 없음", f"{lab(p, 'en')} not measured"))
            level = "block"
            continue
        lo, hi = s.get("lsl"), s.get("usl")
        if (lo is not None and v < lo) or (hi is not None and v > hi):
            reasons.append((f"{lab(p, 'ko')} 규격 이탈 {num(v)}", f"{lab(p, 'en')} out of spec {num(v)}"))
            level = "block"
        elif lo is not None and hi is not None and min(v - lo, hi - v) < 0.05 * (hi - lo):
            reasons.append((f"{lab(p, 'ko')} 규격 경계 {num(v)} (폭의 5% 이내)", f"{lab(p, 'en')} within 5% of a limit ({num(v)})"))
            level = "hold" if level == "release" else level
    if b.t2 is not None and i in b.t2.index and bool(b.t2.loc[i, "alarm"]):
        reasons.append(("다변량 T² 이상 (조합 이상)", "Multivariate T² alarm (unusual combination)"))
        level = "hold" if level == "release" else level
    rank = {"release": 0, "hold": 1, "block": 2}
    for lv, ko, en in (oos.flags(lot, b.dbpath) if oos_flags is None else oos_flags):
        reasons.append((ko, en))
        level = max(level, lv, key=rank.get)
    cc = qms.complaints(b.dbpath)
    if len(cc) and ((cc["lot_id"] == lot) & (cc["status"] == "Open")).any():
        reasons.append(("이 로트에 진행 중인 고객 클레임", "Open customer complaint on this lot"))
        level = "hold" if level == "release" else level
    return level, reasons


def pdf(b, lot: str, customer: str, qty_kg: float = 200, po: str = "", draft: bool = False) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    s = config.specs()["product"]
    r = b.product[b.product["lot_id"] == lot].iloc[0]
    made = pd.to_datetime(r["measured_at"])
    st = getSampleStyleSheet()
    buf = BytesIO()

    def mark(c, _doc):
        c.saveState()
        c.setFont("Helvetica", 7)
        c.setFillGray(0.6)
        c.drawString(18 * mm, 10 * mm, "Synthetic demo document generated by Material Quality Intelligence.")
        if draft:
            c.setFont("Helvetica-Bold", 60)
            c.setFillColorRGB(0.9, 0.3, 0.3, alpha=0.18)
            c.translate(105 * mm, 150 * mm)
            c.rotate(35)
            c.drawCentredString(0, 0, "DRAFT · HOLD")
        c.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title=f"CoA {lot}")
    head = Table([[Paragraph(f"<b><font size=15>{COMPANY}</font></b><br/><br/><font size=8>Electronic materials · "
                             "Quality Assurance</font>", st["Normal"]),
                   Paragraph("<font size=8>QA-F-105 Rev.1</font>", st["Normal"])]], colWidths=[130 * mm, 44 * mm])
    head.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, 0), 1.2, colors.black), ("VALIGN", (0, 0), (-1, -1), "BOTTOM"),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    info = [["Customer", customer, "Lot No.", lot],
            ["Product", s["name"], "PO No.", po or "-"],
            ["Mfg. date", f"{made:%Y-%m-%d}", "Expiry", f"{made + pd.DateOffset(months=6):%Y-%m-%d}"],
            ["Quantity", f"{num(qty_kg)} kg", "Storage", "-40 °C, thaw 1 h before use"]]
    ti = Table(info, colWidths=[24 * mm, 63 * mm, 24 * mm, 63 * mm])
    ti.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("FONTSIZE", (0, 0), (-1, -1), 9),
                            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9")),
                            ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f1f5f9"))]))
    rows = [["No.", "Test item", "Method", "Unit", "Specification", "Result", "Judge"]]
    for k, (p, sp) in enumerate(s["properties"].items(), 1):
        v = r.get(p)
        ok = v is not None and not pd.isna(v) and (sp.get("lsl") is None or v >= sp["lsl"]) and (sp.get("usl") is None or v <= sp["usl"])
        rows.append([str(k), lab(p, "en")[:1].upper() + lab(p, "en")[1:], METHOD.get(p, "-"), sp["unit"], f"{sp.get('lsl')} - {sp.get('usl')}",
                     num(v) if v is not None and not pd.isna(v) else "-", "Pass" if ok else "Fail"])
    tt = Table(rows, colWidths=[10 * mm, 34 * mm, 45 * mm, 16 * mm, 28 * mm, 24 * mm, 17 * mm])
    tt.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("FONTSIZE", (0, 0), (-1, -1), 9),
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
                            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("ALIGN", (5, 1), (5, -1), "RIGHT")]))
    sign = Table([["Tested by (QC)", "Approved by (QA)", "Issue date"],
                  ["", "", f"{pd.Timestamp.today():%Y-%m-%d}"]], colWidths=[58 * mm] * 3, rowHeights=[6 * mm, 14 * mm])
    sign.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("FONTSIZE", (0, 0), (-1, -1), 9),
                              ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9"))]))
    doc.build([head, Spacer(1, 6 * mm), Paragraph("<b><font size=14>CERTIFICATE OF ANALYSIS</font></b>", st["Title"]),
               Spacer(1, 2 * mm), ti, Spacer(1, 6 * mm), tt, Spacer(1, 6 * mm),
               Paragraph("We certify that this lot was tested according to the methods above and conforms to the "
                         "agreed specification.", st["Normal"]), Spacer(1, 8 * mm), sign],
              onFirstPage=mark, onLaterPages=mark)
    return buf.getvalue()


def batch_status(b, n: int = 30) -> pd.DataFrame:
    """Release status of the latest n lots."""
    out, ft = [], oos.flag_table(b.dbpath)
    for lot in b.product["lot_id"].tail(n)[::-1]:
        lvl, why = release_check(b, lot, ft.get(lot, []))
        out.append(dict(lot_id=lot, status=lvl, reasons=why))
    return pd.DataFrame(out)



